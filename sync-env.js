/**
 * Renim AI - Environment Sync Utility
 * Reads .env file and automatically generates config.js for the Chrome Extension runtime.
 */

const fs = require('fs');
const path = require('path');

const envPath = path.join(__dirname, '.env');
const configPath = path.join(__dirname, 'config.js');

function parseEnv(content) {
  const result = {};
  const lines = content.split('\n');
  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const match = trimmed.match(/^([^=]+)=(.*)$/);
    if (match) {
      const key = match[1].trim();
      let value = match[2].trim();
      // Remove enclosing quotes if present
      if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
        value = value.slice(1, -1);
      }
      result[key] = value;
    }
  }
  return result;
}

if (!fs.existsSync(envPath)) {
  console.log('[Sync] No .env file found. Creating from .env.example...');
  if (fs.existsSync(path.join(__dirname, '.env.example'))) {
    fs.copyFileSync(path.join(__dirname, '.env.example'), envPath);
  }
}

const envContent = fs.existsSync(envPath) ? fs.readFileSync(envPath, 'utf8') : '';
const parsed = parseEnv(envContent);

const configContent = `/**
 * Renim AI - Global Environment & Configuration Loader
 * Auto-generated by sync-env.js from .env file.
 */

const ENV_CONFIG = {
  SUPABASE_URL: ${JSON.stringify(parsed.SUPABASE_URL || '')},
  SUPABASE_ANON_KEY: ${JSON.stringify(parsed.SUPABASE_ANON_KEY || '')},
  AI_GATEWAY_URL: ${JSON.stringify(parsed.AI_GATEWAY_URL || 'https://api.openai.com/v1')},
  AI_GATEWAY_API_KEY: ${JSON.stringify(parsed.AI_GATEWAY_API_KEY || '')},
  AI_GATEWAY_MODEL: ${JSON.stringify(parsed.AI_GATEWAY_MODEL || 'gpt-4o-mini')}
};

if (typeof window !== 'undefined') {
  window.ENV_CONFIG = ENV_CONFIG;
}

if (typeof globalThis !== 'undefined') {
  globalThis.ENV_CONFIG = ENV_CONFIG;
}
`;

fs.writeFileSync(configPath, configContent, 'utf8');
console.log('✅ Successfully synced .env credentials into config.js!');
